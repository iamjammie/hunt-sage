#!/usr/bin/env python3
"""Publish the cheat sheets as site pages as well as PDFs.

Reads the markdown sources in scripts/cheatsheets/*.md (the same sources build_cheatsheets.py
turns into PDFs) and writes cheatsheets/<name>.md with front matter so Jekyll renders each
sheet as a searchable, filterable web page at /cheatsheets/<name>/, next to the PDF download.

Usage: python scripts/build_cheatsheet_pages.py            # write the pages
       python scripts/build_cheatsheet_pages.py --check    # exit 1 if pages are stale (CI)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "scripts" / "cheatsheets"
OUT_DIR = ROOT / "cheatsheets"
FM_RE = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.S)

# Display order on the index and in the sidebar; everything else is appended alphabetically.
ORDER = ["windows-event-ids", "sysmon", "linux-logs-auditd", "kql", "splunk-spl", "network-zeek",
         "lolbins", "active-directory-attacks"]


def render(src: Path) -> str:
    text = src.read_text(encoding="utf-8")
    m = FM_RE.match(text)
    fm = yaml.safe_load(m.group(1)) if m else {}
    body = text[m.end():] if m else text
    name = src.stem
    front = {
        "title": fm.get("title", name),
        "permalink": f"/cheatsheets/{name}/",
        "excerpt": fm.get("excerpt", ""),
        "classes": "wide",
        "toc": True,
        "toc_sticky": True,
        "cheatsheet": True,
        "pdf": f"/cheatsheets/{name}.pdf",
        "source": f"scripts/cheatsheets/{name}.md",
    }
    fm_text = yaml.safe_dump(front, sort_keys=False, allow_unicode=True, width=1000).rstrip()
    return (
        f"---\n{fm_text}\n---\n"
        f"<!-- generated by scripts/build_cheatsheet_pages.py from {front['source']}; edit the source, not this file -->\n"
        "{% include cheatsheet-header.html %}\n\n"
        + body.strip() + "\n"
    )


def main() -> int:
    sources = sorted(SRC_DIR.glob("*.md"), key=lambda p: (ORDER.index(p.stem) if p.stem in ORDER else 99, p.stem))
    if not sources:
        print("FAILED: no cheat sheet sources in scripts/cheatsheets/")
        return 1
    outputs = {OUT_DIR / f"{src.stem}.md": render(src) for src in sources}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, txt in outputs.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != txt]
        if stale:
            print("FAILED: cheat sheet pages are stale, run `python scripts/build_cheatsheet_pages.py`:")
            for s in stale:
                print("  -", s)
            return 1
        print(f"OK: {len(outputs)} cheat sheet pages up to date")
        return 0
    for p, txt in outputs.items():
        p.write_text(txt, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
